"use strict";
/* Demo mode: a topbar switch between the sample retail workspace and real data, plus a guided tour of every feature. */

async function demoPill() {
  const el = h("div", { class: "demopill", id: "demo-pill" });
  const draw = (st) => {
    el.replaceChildren(
      st.enabled ? h("span", { class: "chip warn", title: "Sample data generated by Tessera; no real people or companies." }, "Demo data") : null,
      h("button", { class: "sm", onclick: () => startTour(st) }, st.enabled ? "Take the tour" : "Tour"),
      can("admin") ? (st.enabled
        ? h("button", { class: "sm", onclick: () => switchToReal() }, "Switch to real data")
        : h("button", { class: "sm", onclick: () => loadDemo() }, "Load demo")) : null);
  };
  GET("/api/demo").then(draw).catch(() => {});
  return el;
}

async function loadDemo() {
  confirmBox("Load the demo workspace? It adds a sample retail dataset (generated data, no real people), a pipeline, a semantic model, dashboards, alerts, a notebook and targets. You can remove all of it later in one click.",
    "Load demo", async () => {
      toast("Loading demo data, this takes a few seconds…");
      await POST("/api/demo");
      toast("Demo loaded. Starting the tour.");
      await refreshShell();
      startTour({ enabled: true });
    });
}

async function switchToReal() {
  const p = await GET("/api/demo/plan");
  const n = Object.values(p.counts).reduce((a, b) => a + b, 0);
  const built = p.user_built.queries + p.user_built.dashboards;
  dialog("Switch to real data", h("div", { class: "stack" },
    h("p", null, `This removes the demo workspace: ${n} demo items and ${p.tables.length} demo tables. Users, roles, SSO, tokens, workspaces and settings stay.`),
    built ? h("div", { class: "notice warn" }, `${p.user_built.queries} report(s) and ${p.user_built.dashboards} dashboard(s) you built on demo data will also be removed.`) : null,
    h("p", { class: "small muted" }, "Next: add a connection to your own source under Connections, or upload a file. The tour still works on your own data.")),
  [{ label: "Remove demo data", class: "primary danger", run: async () => {
    const r = await DEL("/api/demo");
    toast(`Demo removed (${Object.values(r.deleted).reduce((a, b) => a + b, 0)} items, ${r.tables_dropped} tables).`);
    await refreshShell();
    go("#/connections/new");
  } }]);
}

async function refreshShell() {
  const old = $("#demo-pill");
  if (old) old.replaceWith(await demoPill());
}

/* ---------------- guided tour ---------------- */
async function tourTargets() {
  const [ds, models, dashes, pipes, nbs] = await Promise.all([GET("/api/datasets").catch(() => []), GET("/api/models").catch(() => []), GET("/api/dashboards").catch(() => []),
    can("engineer") ? GET("/api/pipelines").catch(() => []) : [], can("analyst") ? GET("/api/notebooks").catch(() => []) : []]);
  const serving = ds.find((d) => d.schema_name === "serving") || ds[0];
  return { ds: serving?.id, model: (models.find((m) => m.endorsement === "certified") || models[0])?.id, dash: (dashes.find((d) => d.name === "Sales overview") || dashes[0])?.id,
    pipe: pipes[0]?.id, nb: nbs[0]?.id };
}

