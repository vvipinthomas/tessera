async function startTour(st) {
  stopTour();
  const t = await tourTargets();
  const steps = tourSteps(t);
  if (!steps.length) return;
  let i = 0;
  const card = h("div", { class: "tourcard", role: "dialog", "aria-label": "Product tour", id: "tour" });
  document.body.append(card);
  const show = async () => {
    const s = steps[i];
    document.querySelectorAll(".tour-hl").forEach((x) => x.classList.remove("tour-hl"));
    if (location.hash !== "#/" + s.route) { location.hash = "#/" + s.route; await new Promise((r) => setTimeout(r, 700)); }
    if (s.sel) {
      for (let k = 0; k < 20 && !$(s.sel); k++) await new Promise((r) => setTimeout(r, 150));
      const el = $(s.sel);
      if (el) { el.classList.add("tour-hl"); el.scrollIntoView({ block: "center", behavior: "smooth" }); }
    }
    card.replaceChildren(
      h("div", { class: "spread" }, h("span", { class: "eyebrow" }, `Tour · ${i + 1} of ${steps.length}`), h("button", { class: "sm ghost", "aria-label": "End tour", onclick: stopTour }, "✕")),
      h("h3", null, s.title), h("p", { class: "small" }, s.text),
      !st.enabled && i === 0 ? h("p", { class: "small muted" }, "Tip: an admin can load demo data from the top bar to see every screen filled in.") : null,
      h("div", { class: "tourbar" }, h("i", { style: { width: `${((i + 1) / steps.length) * 100}%` } })),
      h("div", { class: "row", style: { justifyContent: "space-between" } },
        h("button", { class: "sm", disabled: i === 0, onclick: () => { i--; show(); } }, "Back"),
        i < steps.length - 1 ? h("button", { class: "sm primary", id: "tour-next", onclick: () => { i++; show(); } }, "Next") : h("button", { class: "sm primary", onclick: stopTour }, "Finish")));
  };
  show();
}

function stopTour() {
  $("#tour")?.remove();
  document.querySelectorAll(".tour-hl").forEach((x) => x.classList.remove("tour-hl"));
}
